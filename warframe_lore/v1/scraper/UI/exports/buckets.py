"""Per-category structured JSON exports with anti-fragmentation consolidation."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ..runtime.artifact_formats import write_json
from .pages import bucket_title, page_record, slug

MAX_RAW_BUCKETS = 12
MIN_BUCKET_PAGES = 3


def write_buckets(
    out_dir: Path,
    docs: list[dict[str, Any]],
    generated_at: str,
) -> list[Path]:
    """Write one metadata + pages JSON file per consolidated bucket and language."""
    groups = _group_pages(docs)
    if len(groups) > MAX_RAW_BUCKETS:
        groups = _consolidate_small_buckets(groups)
    files: list[Path] = []
    for (bucket, language), pages in sorted(groups.items()):
        payload = {
            "metadata": {
                "bucket_title": bucket,
                "generated_at": generated_at,
                "total_pages": len(pages),
                "source_api": _source_api(pages),
                "note": "Generated by Atelier v1 for RAG ingestion.",
            },
            "pages": pages,
        }
        name = f"{slug(bucket)}_{language.upper()}.json"
        files.append(write_json(out_dir / name, payload))
    return files


def _group_pages(
    docs: list[dict[str, Any]],
) -> dict[tuple[str, str], list[dict[str, Any]]]:
    groups: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for doc in docs:
        key = (bucket_title(doc), _language(doc))
        groups.setdefault(key, []).append(page_record(doc))
    return groups


def _consolidate_small_buckets(
    groups: dict[tuple[str, str], list[dict[str, Any]]],
) -> dict[tuple[str, str], list[dict[str, Any]]]:
    """Merge tiny singleton buckets into General_<LANG> on large corpora."""
    merged: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for (bucket, lang), pages in groups.items():
        target = (bucket, lang) if len(pages) >= MIN_BUCKET_PAGES else ("General", lang)
        merged.setdefault(target, []).extend(pages)
    return merged


def _language(doc: dict[str, Any]) -> str:
    value = str(doc.get("language") or "en").strip().lower()
    return value[:2] or "en"


def _source_api(pages: list[dict[str, Any]]) -> str:
    sources = {
        str(page.get("_source") or "") for page in pages
        if page.get("_source")
    }
    return ", ".join(sorted(sources))
